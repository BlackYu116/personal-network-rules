#!/usr/bin/env python3
"""Generate financial domain lists from the reviewed service catalog."""
import argparse
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
POLICIES = {
    'bank-cn-priority': '🏦 银行-内地',
    'finance-priority': '🏦 金融',
    'bank-hk': '🏦 银行-香港',
    'bank-us': '🏦 银行-美国',
    'bank-sg': '🏦 银行-新加坡',
    'bank-cn': '🏦 银行-内地',
    'broker-hk': '📈 券商-香港',
    'broker-us': '📈 券商-美国',
    'broker-sg': '📈 券商-新加坡',
    'broker-futu': '📈 富途/Moomoo',
    'broker-webull': '📈 Webull',
    'broker-tiger': '📈 Tiger',
    'finance': '🏦 金融',
}


def catalog():
    data = yaml.safe_load((ROOT / 'data/financial-services.yaml').read_text())
    assert isinstance(data['services'], list) and data['services']
    owners = {}
    for service in data['services']:
        assert service['name'] and service['policy'] in POLICIES
        assert service['sources'] and all(url.startswith(('https://', 'http://')) for url in service['sources'])
        for kind in ['suffixes', 'exact']:
            assert isinstance(service[kind], list)
            for host in service[kind]:
                assert re.fullmatch(r'[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?', host), 'Not a lowercase host: ' + host
                assert '.' in host and '..' not in host
                entry = ('+.' if kind == 'suffixes' else '') + host
                assert owners.get(entry, service['policy']) == service['policy'], 'Ambiguous financial exception: ' + entry
                owners[entry] = service['policy']
    return data


def outputs(data):
    result = {}
    for policy in POLICIES:
        entries = []
        names = []
        for service in data['services']:
            if service['policy'] != policy:
                continue
            names.append(service['name'])
            entries.extend('+.' + host for host in service['suffixes'])
            entries.extend(service['exact'])
        entries = list(dict.fromkeys(entries))
        assert entries, 'Empty financial policy: ' + policy
        header = ('# Generated by scripts/gen_financial_rules.py; edit data/financial-services.yaml.\n'
                  '# Domains identify the reviewed service route, not the IP country or account jurisdiction.\n'
                  '# Sources, shared-host boundaries and institutions: docs/financial-coverage.md.\n')
        result[ROOT / 'rules' / (policy + '.yaml')] = header + yaml.safe_dump({'payload': entries}, sort_keys=False)
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = catalog()
    for path, content in outputs(data).items():
        if args.check:
            assert path.exists() and path.read_text() == content, 'Financial list out of sync: ' + path.name
        else:
            path.write_text(content)
    print(f'Financial catalog: {len(data["services"])} reviewed records, {len(POLICIES)} synchronized lists.')


if __name__ == '__main__':
    main()
